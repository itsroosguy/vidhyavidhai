export function getExportColumnDeclaration(
  spec: ExportColumnSpec,
): {
  category: WorkbookColumnMeta['category'];
  dataType: string;
  validationRule: string;
  definition: string;
  meta?: StandardExportFieldMeta;
} {
  const matched = STANDARD_EXPORT_FIELD_DECLARATIONS.find((m) => m.sourceKey === spec.sourceKey);
  if (matched) {
    return {
      category: matched.category,
      dataType: matched.dataType,
      validationRule: matched.validationRule,
      definition: matched.definition,
      meta: matched,
    };
  }
  return {
    category: 'Programme & Tour',
    dataType: spec.format === 'number' ? 'Integer' : spec.format === 'decimal2' ? 'Decimal (0.00)' : 'Text (@)',
    validationRule: spec.format === 'constant' ? `Constant: ${spec.constantValue ?? ''}` : 'Custom 63-column template mapping',
    definition: spec.sourceKey
      ? `Mapped to internal reporting field "${spec.sourceKey}".`
      : 'Unmapped custom partner template column reserved by uploaded 63-column schema.',
  };
}
